"""Evaluation of the recommender and the skill extractor.

1. Recommender: 264 labelled SYNTHETIC resumes (12 per role, generated by scripts/make_data.py with
   deliberately mixed-in skills from neighbouring roles). Metrics: top-1 / top-3 / top-5 accuracy and
   mean reciprocal rank (MRR), plus an ablation study of the three score components.
2. Skill extraction: precision / recall / F1 on the 5 sample resume PDFs against a manually audited answer key.
"""
import json
from collections import Counter

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from src import config
from src.pdf_parser import extract_text
from src.recommender import load_model, recommend
from src.resume_parser import parse_resume

VARIANTS = {
    "Text similarity only (TF-IDF)": (1.0, 0.0, 0.0),
    "Skill coverage only": (0.0, 1.0, 0.0),
    "Text + skills (no fit)": (0.55, 0.45, 0.0),
    "Combined (default weights)": (config.W_TEXT, config.W_SKILLS, config.W_FIT),
}


def evaluate_recommender() -> dict:
    df = pd.read_csv(config.EVAL_CSV)
    model = load_model()
    parsed = [parse_resume(t) for t in df["resume_text"]]
    n_roles = len(model["roles"])
    out = {"n_resumes": len(df), "n_roles": n_roles, "random_top1": round(1 / n_roles, 4), "variants": {}}
    default_ranks = None
    for name, w in VARIANTS.items():
        ranks = []
        for resume, truth in zip(parsed, df["true_role"]):
            order = [r["role"] for r in recommend(resume, model, top_k=0, weights=w)]
            ranks.append(order.index(truth) + 1)
        s = pd.Series(ranks)
        out["variants"][name] = {"top1": round((s <= 1).mean(), 4), "top3": round((s <= 3).mean(), 4), "top5": round((s <= 5).mean(), 4), "mrr": round((1 / s).mean(), 4)}
        if name.startswith("Combined"):
            default_ranks = ranks
    # per-role top-1 and most common confusions for the default model
    per_role, confusions = {}, Counter()
    for resume, truth in zip(parsed, df["true_role"]):
        top = recommend(resume, model, top_k=1)[0]["role"]
        per_role.setdefault(truth, []).append(top == truth)
        if top != truth:
            confusions[(truth, top)] += 1
    out["per_role_top1"] = {k: round(sum(v) / len(v), 3) for k, v in per_role.items()}
    out["top_confusions"] = [{"true": t, "predicted": p, "count": c} for (t, p), c in confusions.most_common(6)]
    return out


def evaluate_skill_extraction() -> dict:
    gold = json.loads((config.SAMPLE_RESUME_DIR / "gold_skills.json").read_text())
    tp = fp = fn = 0
    per, errors = {}, []
    for fname, truth in gold.items():
        pred = set(parse_resume(extract_text(config.SAMPLE_RESUME_DIR / fname))["skills"])
        truth = set(truth)
        t, f_p, f_n = len(pred & truth), len(pred - truth), len(truth - pred)
        tp, fp, fn = tp + t, fp + f_p, fn + f_n
        per[fname] = {"precision": round(t / (t + f_p), 3) if t + f_p else 0.0, "recall": round(t / (t + f_n), 3) if t + f_n else 0.0}
        if f_p or f_n:
            errors.append({"file": fname, "extra (false positives)": sorted(pred - truth), "missed (false negatives)": sorted(truth - pred)})
    p, r = tp / (tp + fp), tp / (tp + fn)
    return {"precision": round(p, 4), "recall": round(r, 4), "f1": round(2 * p * r / (p + r), 4), "n_resumes": len(gold), "per_resume": per, "errors": errors}


def run_evaluation(verbose=True) -> dict:
    config.OUT_DIR.mkdir(exist_ok=True)
    rec, ext = evaluate_recommender(), evaluate_skill_extraction()
    result = {"recommender": rec, "skill_extraction": ext}
    (config.OUT_DIR / "evaluation.json").write_text(json.dumps(result, indent=2))

    var = pd.DataFrame(rec["variants"]).T
    fig, ax = plt.subplots(figsize=(8, 4.5))
    var[["top1", "top3", "top5", "mrr"]].plot.bar(ax=ax)
    ax.axhline(rec["random_top1"], color="grey", ls="--", lw=1, label=f"random top-1 ({rec['random_top1']:.2f})")
    ax.set_ylim(0, 1.05); ax.set_title("Recommender ablation (264 synthetic labelled resumes)"); plt.xticks(rotation=18, ha="right"); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(config.OUT_DIR / "recommender_ablation.png", dpi=140); plt.close(fig)
    pr = pd.Series(rec["per_role_top1"]).sort_values()
    fig, ax = plt.subplots(figsize=(7, 6)); pr.plot.barh(ax=ax, color="#3b82f6"); ax.set_xlim(0, 1.05); ax.set_title("Top-1 accuracy per role (default model)")
    fig.tight_layout(); fig.savefig(config.OUT_DIR / "per_role_accuracy.png", dpi=140); plt.close(fig)

    _write_report(result, var)
    if verbose:
        print(f"=== Career recommender: {rec['n_resumes']} synthetic labelled resumes, {rec['n_roles']} roles (random guess top-1 = {rec['random_top1']:.1%}) ===")
        print(var.rename(columns={"top1": "top-1", "top3": "top-3", "top5": "top-5", "mrr": "MRR"}).to_string())
        print("\nMost common mix-ups (true -> predicted):")
        for c in rec["top_confusions"][:5]:
            print(f"  {c['true']} -> {c['predicted']}: {c['count']}")
        print(f"\n=== Skill extraction on {ext['n_resumes']} sample resume PDFs ===")
        print(f"precision {ext['precision']:.3f} | recall {ext['recall']:.3f} | F1 {ext['f1']:.3f}")
        for e in ext["errors"]:
            print(f"  {e['file']}: extra={e['extra (false positives)']} missed={e['missed (false negatives)']}")
        print("\nReport written to docs/Evaluation_Report.md")
    return result


